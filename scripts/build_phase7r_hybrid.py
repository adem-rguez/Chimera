    if out_rows:
        print("  3 examples (tail of prefix_text, around the forced close):")
        for r in out_rows[:3]:
            print(f"\n    {r['id']} tail={r['tail_text']!r}:")
            print(f"    ...{r['prefix_text'][-250:]!r}")
    return out_rows


