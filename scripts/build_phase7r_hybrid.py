def build_hybrid_row(tok, row, canonical, splice_offset=None):
    """row: one organic trace dict (filtered, agreed if decision). canonical: {type: (instr, opt_keys)}
    from check_phase7r_pilot.load_canonical. Returns the output row dict (rule 4 schema), or raises for a
    genuine bug (never for a drop condition -- callers decide drops before calling this)."""
    is_decision = row["kind"] == "decision"
    user, answer, thinking = row["user"], row["answer"], row["thinking"]

    if is_decision:
        gold, tname = row["gold_label"], row["type"]
        options_kv = row["options_with_descriptions"]
        instr, _opts = canonical[tname]
        options = [option_text(k, d) for k, d in options_kv]
        calls = [{"type": tname, "instruction": instr, "options": options, "gold_label": gold}]
        kept = thinking[:splice_offset].rstrip()
        tail = tail_for(row["id"], gold)
        segs = [kept, tail]
        reasoning_short = build_reasoning(calls, segs)
        decision_types = [tname]
        label_surfaces = {gold: label_surface(gold)}
        kind = "call"
    else:
        calls, segs, decision_types, label_surfaces, kind = [], [thinking], [], {}, "control"
        reasoning_short = thinking

    reasoning_long = thinking

    full_short, plen_short = render_hybrid(tok, user, reasoning_short, answer)
    full_long, plen_long = render_hybrid(tok, user, reasoning_long, answer)

    injected = injected_spans_typed(full_short)
    if injected_spans_typed(full_long):
        raise ValueError(f"{row['id']}: thinking_long contains trigger/result markers")
    if is_decision and len(injected) != 1:
        raise ValueError(f"{row['id']}: expected exactly 1 injected span, found {len(injected)}")
    if not is_decision and injected:
        raise ValueError(f"{row['id']}: control row has {len(injected)} injected span(s)")

    acct_short = token_accounting(tok, full_short, plen_short, injected)
    acct_long = token_accounting(tok, full_long, plen_long, [])
    masked_spans_short = [[0, plen_short]] + [[s, e] for s, e in injected]

    organic_tok = decoded_think_tokens(tok, thinking)
    hybrid_tok = decoded_think_tokens(tok, reasoning_short) if is_decision else organic_tok

    return {
        "id": row["id"], "kind": kind, "source": "H", "decision_types": decision_types,
        "adversarial": row["kind"] == "adversarial", "user": user,
        "calls": calls, "label_surfaces": label_surfaces, "answer": answer,
        "thinking_segments": segs, "thinking_long": reasoning_long,
        "target_text_short": full_short, "target_text_long": full_long,
        "masked_spans_short": masked_spans_short,
        "tokens_short": acct_short, "tokens_long": acct_long,
        "delta_supervised": acct_long["tokens_supervised"] - acct_short["tokens_supervised"],
        "delta_total": (acct_long["tokens_total"] - acct_long["tokens_prompt_masked"]) -
                        (acct_short["tokens_total"] - acct_short["tokens_prompt_masked"]),
        "organic_thinking_tokens": organic_tok, "hybrid_thinking_tokens": hybrid_tok,
        "saved_tokens": organic_tok - hybrid_tok,
        "splice_char": splice_offset if is_decision else None,
    }


def build(args):
    organic_path = args.organic if os.path.isabs(args.organic) else os.path.join(ROOT, args.organic)
    out_path = args.out if os.path.isabs(args.out) else os.path.join(ROOT, args.out)
    natural_path = os.path.join(ROOT, NATURAL_EVAL)

    rows = [json.loads(l) for l in open(organic_path, encoding="utf-8") if l.strip()]
    if args.limit:
        rows = rows[:args.limit]
    print(f"loaded {len(rows)} rows from {args.organic}")

    eval_ids, eval_refs = load_eval_keys(natural_path)
    n_dev_hits = guard_dev_leak(rows, eval_ids, eval_refs, args.dev, out_path)
    if n_dev_hits:
        print(f"--dev: {n_dev_hits} input rows overlap {NATURAL_EVAL} by id/item_ref (expected for "
              f"development against eval-shaped data; NOT written unless --dev)")

    canonical, canon_errs = load_canonical(os.path.join(ROOT, SUITE))
    if canon_errs:
        raise SystemExit(f"load_canonical errors: {canon_errs}")

    extract_by_id = load_extract(args.extract if not args.extract or os.path.isabs(args.extract)
                                  else os.path.join(ROOT, args.extract))

    tok = get_tokenizer(args.model, args.revision)

    drop_reasons = collections.Counter()
    drop_by_type = collections.defaultdict(collections.Counter)
    kept = []
    examples_by_reason = collections.defaultdict(list)

    for row in rows:
        rid, rtype = row["id"], row.get("type")
        if not row.get("finished"):
            drop_reasons["not_finished"] += 1
            drop_by_type[rtype]["not_finished"] += 1
            continue
        if not row.get("thinking") or not row.get("answer"):
            drop_reasons["empty_thinking_or_answer"] += 1
            drop_by_type[rtype]["empty_thinking_or_answer"] += 1
            continue
        if row.get("n_thinking_tokens", 0) > MAX_THINK_TOKENS:
            drop_reasons["over_max_think_tokens"] += 1
            drop_by_type[rtype]["over_max_think_tokens"] += 1
            continue

        if row["kind"] != "decision":
            built = build_hybrid_row(tok, row, canonical)
            kept.append(built)
            continue

        agree, reason = check_agreement(row, extract_by_id)
        if agree is not True:
            tag = "disagree" if agree is False else "no_signal"
            drop_reasons[tag] += 1
            drop_by_type[rtype][tag] += 1
            if len(examples_by_reason[tag]) < 2:
                examples_by_reason[tag].append((rid, reason, row["gold_label"], row["answer"][:200]))
            continue

        option_keys = [k for k, _d in row["options_with_descriptions"]]
        splice_offset, splice_reason = find_splice(row["thinking"], row["gold_label"], option_keys)
        if splice_offset is None:
            drop_reasons[f"no_splice:{splice_reason}"] += 1
            drop_by_type[rtype][f"no_splice:{splice_reason}"] += 1
            if len(examples_by_reason[f"no_splice:{splice_reason}"]) < 2:
                examples_by_reason[f"no_splice:{splice_reason}"].append(
                    (rid, splice_reason, row["gold_label"], row["thinking"][:300]))
            continue

        built = build_hybrid_row(tok, row, canonical, splice_offset=splice_offset)
        kept.append(built)

    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as f:
        for r in kept:
            f.write(json.dumps(r) + "\n")

    # ---- summary ----
    n_decision_in = sum(1 for r in rows if r["kind"] == "decision")
    n_control_in = len(rows) - n_decision_in
    n_kept_call = sum(1 for r in kept if r["kind"] == "call")
    n_kept_ctrl = sum(1 for r in kept if r["kind"] == "control")
    print(f"\nbuilt {len(kept)} rows -> {out_path}")
    print(f"  input: {len(rows)} ({n_decision_in} decision, {n_control_in} control/adversarial)")
    print(f"  kept:  {len(kept)} ({n_kept_call} call, {n_kept_ctrl} control)")
    print(f"  dropped: {sum(drop_reasons.values())}, by reason: {dict(drop_reasons)}")
    print("  dropped by type:")
    for t, ctr in sorted(drop_by_type.items()):
        print(f"    {t}: {dict(ctr)}")

    decision_per_type = collections.Counter(r.get("type") for r in rows if r["kind"] == "decision")
    kept_decision_ids = {r["id"] for r in kept if r["kind"] == "call"}
    for t in sorted(decision_per_type):
        n_in = decision_per_type[t]
        n_out = sum(1 for r in kept if r["kind"] == "call" and r["decision_types"] == [t])
        n_disagree = drop_by_type[t].get("disagree", 0) + drop_by_type[t].get("no_signal", 0)
        print(f"  type {t}: {n_in} in -> {n_out} kept, {n_disagree} agreement-dropped "
              f"({n_disagree/n_in:.1%})" if n_in else f"  type {t}: 0 in")

    call_rows = [r for r in kept if r["kind"] == "call"]
    if call_rows:
        org = [r["organic_thinking_tokens"] for r in call_rows]
        hyb = [r["hybrid_thinking_tokens"] for r in call_rows]
        saved = [r["saved_tokens"] for r in call_rows]
        mean_org, mean_hyb, mean_saved = sum(org) / len(org), sum(hyb) / len(hyb), sum(saved) / len(saved)
        print(f"\n  thinking tokens: organic mean {mean_org:.1f}, hybrid mean {mean_hyb:.1f}, "
              f"saved mean {mean_saved:.1f} ({mean_saved / mean_org:.1%})")

    for reason, examples in sorted(examples_by_reason.items()):
        print(f"\n  examples for drop reason {reason!r}:")
        for rid, why, gold, snippet in examples:
            print(f"    {rid} gold={gold!r} ({why}): {snippet!r}")

    if call_rows:
        print("\n  3 decoded examples around the splice:")
        for r in call_rows[:3]:
            trig = TRIGGER_FOR[r["decision_types"][0]]
            idx = r["target_text_short"].find(trig)
            lo, hi = max(0, idx - 150), idx + len(trig) + 200
            print(f"\n    {r['id']} splice_char={r['splice_char']} saved={r['saved_tokens']}:")
            print(f"    ...{r['target_text_short'][lo:hi]!r}...")

    return kept


