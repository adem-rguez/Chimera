def validate(args):
    rows_path = args.rows if os.path.isabs(args.rows) else os.path.join(ROOT, args.rows)
    if args.dev and "dev" not in os.path.basename(rows_path).lower():
        raise SystemExit(f"--dev requires --rows to contain 'dev' in its filename (got {rows_path!r})")
    rows = [json.loads(l) for l in open(rows_path, encoding="utf-8") if l.strip()]
    print(f"validate: {len(rows)} rows from {args.rows}")

    fails = []

    def bad(rid, msg):
        fails.append(f"{rid}: {msg}")

    for r in rows:
        rid = r["id"]
        full = r["target_text_short"]
        n_calls = len(r["calls"])
        n_trigger = sum(full.count(t) for t in TRIGGER_FOR.values())
        if r["kind"] == "call":
            if n_trigger != 1 or n_calls != 1:
                bad(rid, f"decision row has {n_trigger} triggers / {n_calls} calls, expected exactly 1 each")
            c = r["calls"][0] if r["calls"] else {}
            if c.get("type") not in SHIPPED_TYPES:
                bad(rid, f"call type {c.get('type')!r} not a shipped type")
            spans = injected_spans_typed(full)
            if len(spans) != 1:
                bad(rid, f"{len(spans)} injected spans, expected 1")
            else:
                s, e = spans[0]
                trig = TRIGGER_FOR[c.get("type")]
                trig_idx = full.find(trig)
                instr_start = trig_idx + len(trig)
                if s != instr_start:
                    bad(rid, f"injected span start {s} != end of trigger {instr_start}")
                want_prefix = f"{c.get('instruction')} [{', '.join(c.get('options', []))}]{RESULT_OPEN}"
                if full[s:s + len(want_prefix)] != want_prefix:
                    bad(rid, "injected span does not start with INSTR [options]<|result|>")
                result_text = full[s + len(want_prefix):e - len(RESULT_CLOSE)]
                if result_text != c.get("gold_label"):
                    bad(rid, f"result text {result_text!r} != gold_label {c.get('gold_label')!r}")
                if full[e - len(RESULT_CLOSE):e] != RESULT_CLOSE:
                    bad(rid, "injected span does not end with <|/result|>")
        else:
            if n_trigger != 0 or n_calls != 0:
                bad(rid, f"control row has {n_trigger} triggers / {n_calls} calls, expected 0")

        if r["target_text_long"].count("<|decide:") or RESULT_OPEN in r["target_text_long"]:
            bad(rid, "target_text_long contains trigger/result markers")
        if full.count("<|think|>\n") != 1:
            bad(rid, f"target_text_short has {full.count(chr(10).join(['<|think|>','']))} "
                     f"'<|think|>' markers, expected exactly 1 (no duplication)")

    ids = [r["id"] for r in rows]
    if len(set(ids)) != len(ids):
        fails.append(f"duplicate ids: {[k for k, v in collections.Counter(ids).items() if v > 1]}")

    # encode_think masking check, same contract as scripts/test_encode_think.py
    from scripts.train_phase7 import encode_think
    tok = get_tokenizer(args.model, args.revision)
    n_mask_checked = n_mask_failed = 0
    for r in rows:
        for variant in ("short", "long"):
            enc = encode_think(tok, r, max_len=4096, variant=variant, user_turn_cap=10_000)
            if enc is None:
                continue
            text = r[f"target_text_{variant}"]
            offs = tok(text, return_offsets_mapping=True, add_special_tokens=False)["offset_mapping"]
            prompt_end = r["masked_spans_short"][0][1]
            spans = r["masked_spans_short"] if variant == "short" else [[0, prompt_end]]
            n_mask_checked += 1
            ok = True
            for i, (a, b) in enumerate(offs):
                should_mask = any(a < e and b > s for s, e in spans)
                is_masked = enc["labels"][i].item() == -100
                if should_mask != is_masked:
                    ok = False
                    break
            if r["kind"] == "call" and variant == "short":
                trig = f"<|decide:{r['calls'][0]['type']}|>"
                idx = text.find(trig)
                trig_end = idx + len(trig)
                trig_labels = [enc["labels"][i].item() for i, (a, b) in enumerate(offs)
                               if a < trig_end and b > idx]
                if not trig_labels or all(l == -100 for l in trig_labels):
                    ok = False
            last_turn = text.rfind("<turn|>")
            turn_end = last_turn + len("<turn|>")
            turn_labels = [enc["labels"][i].item() for i, (a, b) in enumerate(offs)
                           if a < turn_end and b > last_turn]
            if not turn_labels or any(l == -100 for l in turn_labels):
                ok = False
            if not ok:
                n_mask_failed += 1
                bad(r["id"], f"encode_think masking check failed ({variant})")
    print(f"encode_think masking check: {n_mask_checked} (row, variant) pairs checked, "
          f"{n_mask_failed} failed")

    if fails:
        print(f"\nFAILED: {len(fails)} problem(s)")
        for fl in fails[:50]:
            print(f"  - {fl}")
        return 1
    print("all checks passed")
    return 0


