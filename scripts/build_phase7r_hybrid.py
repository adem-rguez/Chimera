def _word_hit(terms, text_lower):
    return any(re.search(r"\b" + re.escape(t) + r"\b", text_lower) for t in terms if t)


def load_extract(path):
    if not path:
        return {}
    out = {}
    with open(path, encoding="utf-8") as f:
        for line in f:
            if line.strip():
                rec = json.loads(line)
                out[rec["id"]] = rec
    return out


def check_agreement(row, extract_by_id):
    """-> (agree: bool|None, reason: str). None means "no reliable signal; drop"."""
    gold = row["gold_label"]
    ext = extract_by_id.get(row["id"])
    if ext is not None:
        return (ext.get("chosen") == gold), "extract"

    answer_l = row["answer"].lower()
    gold_hit = _word_hit(leak_terms(gold), answer_l)
    other_hits = [k for k, _d in row["options_with_descriptions"] if k != gold
                  and _word_hit(leak_terms(k), answer_l)]
    if gold_hit and not other_hits:
        return True, "regex_agree"
    if not gold_hit and other_hits:
        return False, "regex_disagree"
    if gold_hit and other_hits:
        return False, "regex_ambiguous"
    return None, "regex_no_signal"


