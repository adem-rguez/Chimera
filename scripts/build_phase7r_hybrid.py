def load_eval_keys(path):
    ids, item_refs = set(), set()
    if not os.path.exists(path):
        return ids, item_refs
    with open(path, encoding="utf-8") as f:
        for line in f:
            if not line.strip():
                continue
            rec = json.loads(line)
            if rec.get("id"):
                ids.add(rec["id"])
            if rec.get("item_ref"):
                item_refs.add(rec["item_ref"])
    return ids, item_refs


def guard_dev_leak(rows, eval_ids, eval_refs, dev, out_path):
    hit_ids = [r["id"] for r in rows if r.get("id") in eval_ids or r.get("item_ref") in eval_refs]
    if hit_ids and not dev:
        raise SystemExit(
            f"REFUSING: {len(hit_ids)} input row(s) have an id/item_ref present in {NATURAL_EVAL} "
            f"(eval data) -- e.g. {hit_ids[:5]}. Pass --dev if this is an intentional development run "
            f"against eval-shaped data (--dev also requires --out to contain 'dev').")
    if dev and "dev" not in os.path.basename(out_path).lower():
        raise SystemExit(
            f"--dev requires --out to contain the substring 'dev' in its filename (got {out_path!r})")
    return len(hit_ids)


