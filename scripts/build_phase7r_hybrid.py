def _key_variants(key):
    return {key.lower(), key.lower().replace("_", " "), key.lower().replace("_", "-")}


def find_splice(thinking, gold, option_keys, min_chars=MIN_SPLICE_CHARS):
    """-> (offset: int|None, reason: str). offset is the char index in `thinking` where the commit line
    starts (the splice point); None + a reason explains why no valid splice point exists."""
    gold_terms = leak_terms(gold)
    lines = thinking.split("\n")
    offset = 0
    for line in lines:
        line_l = line.lower()
        if _word_hit(gold_terms, line_l):
            enum_count = sum(1 for k in option_keys if any(_word_hit([v], line_l) for v in _key_variants(k)))
            if enum_count >= 2:
                offset += len(line) + 1
                continue  # enumeration line (names >=2 options), not a real commitment -- keep scanning
            if offset < min_chars:
                return None, "commit_too_early"
            return offset, "ok"
        offset += len(line) + 1
    return None, "no_commit_line"


# ---------------------------------------------------------------------------
# splice point for `prefix` mode (rule A) -- generalized for answer_type/kb_category/news_topic, whose
# prompts never list the canonical option keys, so the base model's organic thinking enumerates
# candidates in ITS OWN taxonomy ("Food and Drink", "Organized Crime", ...), not the suite's option
# vocabulary -- find_splice's gold/option-key word-hit approach therefore almost never fires on these rows
# (rule 1's ~70% agreement-drop in the module docstring). Instead: split `thinking` into TOP-LEVEL
# numbered steps (lines matching STEP_RE), find the first line anywhere whose (markdown-stripped) text
# matches PREFIX_TRIGGER_RE -- phrasing the model reliably uses right before it starts naming/listing
# candidate categories/answer-types/tags ("Potential Answer Categories", "Determine the Best Answer
# Type", "Conclusion:", ...) -- and cut at the START of the top-level step that line falls inside (never
# mid-bullet, mid-sentence: the only valid cut points are top-level step boundaries, which are always
# preceded by a newline in this data). Preference: keep the first min(enum_step_idx, 3) steps (reports/16
# "2nd-3rd analysis step" preference), but only once that boundary reaches >=150 chars; if even the
# step right before the enumeration step is short of 150 chars, there wasn't enough restating/
# understanding before the model started naming candidates and the row has no valid splice."""
STEP_RE = re.compile(r"^(\d+)\.\s", re.M)
PREFIX_TRIGGER_RE = re.compile(
    "|".join([
        r"potential\s+(answer|categor|audienc|use[\s-]?case)",
        r"determine\s+(the\s+)?potential",
        r"identify\s+potential",
        r"evaluate\s+.*\bcategor",
        r"select the (most|best)",
        r"choose the (most|best)",
        r"determine the (best|most|appropriate|likely)\b",
        r"final (tag|category|answer|selection)",
        r"formulate the answer",
        r"\bconclusion\b",
        r"classify the answer",
        r"tag selection",
        r"best fit",
        r"most (precise|specific|appropriate|accurate) categor",
        r"select (the )?appropriate",
        r"identify the best answer",
        r"answer type categor",
        r"best answer type",
    ]), re.I)


def find_splice_prefix(thinking, min_chars=MIN_SPLICE_CHARS, prefer_step=3):
    """-> (offset: int|None, reason: str). See module note above `STEP_RE`/`PREFIX_TRIGGER_RE` for the
    algorithm; offset is always the char index of a top-level numbered step's start (never mid-line)."""
    starts = [m.start() for m in STEP_RE.finditer(thinking)]
    if not starts:
        return None, "no_steps"
    starts_ext = starts + [len(thinking)]

    lines = thinking.split("\n")
    line_offsets, pos = [], 0
    for ln in lines:
        line_offsets.append(pos)
        pos += len(ln) + 1

    trig_off = None
    for off, ln in zip(line_offsets, lines):
        if PREFIX_TRIGGER_RE.search(ln.replace("*", "")):
            trig_off = off
            break
    if trig_off is None:
        return None, "no_enumeration_found"

    enum_idx = None
    for i in range(len(starts)):
        if starts[i] <= trig_off < starts_ext[i + 1]:
            enum_idx = i
            break
    if enum_idx is None:
        return None, "commit_too_early_preamble"  # trig_off falls before the first numbered step
    if enum_idx == 0:
        return None, "commit_too_early_step0"  # enumeration starts in step 1 itself -- no room to splice

    target_idx = min(enum_idx, prefer_step)
    while target_idx >= 1 and starts[target_idx] < min_chars:
        target_idx += 1
        if target_idx > enum_idx:
            return None, "commit_too_early"
    return starts[target_idx], "ok"


