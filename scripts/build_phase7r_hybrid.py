def render_hybrid(tok, user, reasoning, answer):
    messages = [{"role": "user", "content": user}]
    prompt = tok.apply_chat_template(messages, tokenize=False, add_generation_prompt=True,
                                      enable_thinking=True)
    full = tok.apply_chat_template(
        messages + [{"role": "assistant", "content": answer, "reasoning": reasoning}],
        tokenize=False, add_generation_prompt=False, enable_thinking=True)
    if not full.startswith(prompt):
        raise ValueError("chat template render did not produce prompt as an exact prefix")
    return full, len(prompt)


def decoded_think_tokens(tok, text):
    """Decoded (non-injected) token count of a thinking string in isolation -- used for the
    organic/hybrid/saved token accounting fields; injected spans never appear in a bare `thinking` string
    by construction (the trigger+injected text is only ever assembled inside build_hybrid_row)."""
    return len(tok(text, add_special_tokens=False)["input_ids"])


