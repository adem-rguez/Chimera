    prefixes = {}
    with open(prefixes_path, encoding="utf-8") as f:
        for line in f:
            if line.strip():
                rec = json.loads(line)
                prefixes[rec["id"]] = rec
    answers = {}
    with open(answers_path, encoding="utf-8") as f:
        for line in f:
            if line.strip():
                rec = json.loads(line)
                answers[rec["id"]] = rec
    if args.limit:
        prefixes = dict(list(prefixes.items())[:args.limit])
    print(f"loaded {len(prefixes)} tailprefix rows from {args.prefixes}, {len(answers)} answer "
          f"generations from {args.answers}")

