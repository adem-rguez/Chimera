    kept = call_rows + control_rows
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as f:
        for r in kept:
            f.write(json.dumps(r) + "\n")

    print(f"\nbuild3: {len(kept)} rows -> {out_path} ({len(call_rows)} call, {len(control_rows)} control)")
    print(f"  call drop reasons: {dict(drop_reasons)}")
    print(f"  control drop reasons (from {len(organic_rows)} organic rows): {dict(control_drop)}")
    if n_checked:
        print(f"  gold label surface mentioned in answer: {n_gold_mentioned}/{n_checked} "
              f"({n_gold_mentioned / n_checked:.1%})")
        print(f"  contradiction (answer names another option, not gold -- DROPPED): {n_contradiction}/"
              f"{n_checked} ({n_contradiction / n_checked:.1%})")

    if call_rows:
        org = [r["organic_thinking_tokens"] for r in call_rows]
        hyb = [r["hybrid_thinking_tokens"] for r in call_rows]
        saved = [r["saved_tokens"] for r in call_rows]
        mean_org, mean_hyb = sum(org) / len(org), sum(hyb) / len(hyb)
        mean_saved = sum(saved) / len(saved)
        print(f"\n  call rows thinking tokens: organic mean {mean_org:.1f}, hybrid mean {mean_hyb:.1f}, "
              f"saved mean {mean_saved:.1f} ({mean_saved / mean_org:.1%})")

        ans_tok = [len(tok(r["answer"], add_special_tokens=False)["input_ids"]) for r in call_rows]
        org_ans_tok = [len(tok(prefixes[r["id"]]["organic_answer"], add_special_tokens=False)["input_ids"])
                       for r in call_rows]
        mean_ans, mean_org_ans = sum(ans_tok) / len(ans_tok), sum(org_ans_tok) / len(org_ans_tok)
        mean_total_hyb, mean_total_org = mean_hyb + mean_ans, mean_org + mean_org_ans
        print(f"  mean answer tokens: hybrid {mean_ans:.1f}, organic {mean_org_ans:.1f}")
        print(f"  mean total decoded tokens (thinking+answer): hybrid {mean_total_hyb:.1f}, "
              f"organic {mean_total_org:.1f} ({(mean_total_org - mean_total_hyb) / mean_total_org:.1%} "
              f"saving)")

        print("\n  3 decoded examples (around the splice AND the forced close/answer):")
        for r in call_rows[:3]:
            trig = TRIGGER_FOR[r["decision_types"][0]]
            idx = r["target_text_short"].find(trig)
            lo, hi = max(0, idx - 100), idx + len(trig) + 350
            print(f"\n    {r['id']} splice_char={r['splice_char']} saved={r['saved_tokens']} "
                  f"gold_mentioned={r['gold_mentioned']}:")
            print(f"    ...{r['target_text_short'][lo:hi]!r}...")
    return kept


