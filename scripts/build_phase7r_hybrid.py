"""Phase 7R "Source H": build hybrid training rows from the base model's OWN organic thinking traces,
with a spliced decision trigger -- see reports/16/17/19 and build_phase7r.py/train_phase7.py (reused, not
re-implemented: exact call-expansion format, chat-template rendering technique, masked-span accounting,
encode_think's masking contract).

Why: authored-prose Stage A/B rows (build_phase7r.py) did not transfer a natural trigger rate (2.3%,
reports/19 arm B finding). Source H instead takes the base model's own organic `thinking` (generated by
scripts/gen_think_traces.py over oracle/phase7r-hybrid-prompts.jsonl -- 1250 train prompts) and SPLICES
a typed trigger into it at a natural decision-commitment point, dropping everything the organic trace said
after that point (that's where the token saving comes from) and replacing it with the canonical injected
call + a short "So it's {label}." style tail, so the model's own voice/register survives everywhere except
the spliced boundary.

DEV SAFETY: oracle/phase7r-hybrid-organic.jsonl (the real Source H input) was still generating on a GPU box
at the time this was written. Development/testing happens against oracle/t3-armB-think.fixed.jsonl instead
(same row schema -- see module-level ROW FORMAT note below) -- it is EVAL data (same ids as
oracle/phase7r-natural-eval.jsonl, joined by id in scripts/extract_labels_llm.py) and must NEVER leak into
a real training output. `build` therefore refuses to run if any input row's id or item_ref is present in
oracle/phase7r-natural-eval.jsonl, UNLESS --dev is passed; --dev additionally refuses to write anywhere
--out doesn't contain the literal substring "dev" (case-insensitive), so a dev run cannot overwrite a real
training file by accident.

ROW FORMAT (organic input, one line per row): every key gen_think_traces.py passes through from
oracle/phase7r-hybrid-prompts.jsonl (id, user, kind in {"decision","control"} (dev file also has
"adversarial"; treated the same as "control" here -- no gold_label to splice against), type, gold_label,
options_with_descriptions, item_ref, label_surfaces) PLUS thinking/answer/raw_text/n_thinking_tokens/
n_answer_tokens/finished.

Row filter (rule 1): finished, non-empty thinking+answer, n_thinking_tokens <= 900. Decision rows
additionally require the organic ANSWER to agree with gold_label -- judged by `--extract FILE`
(scripts/extract_labels_llm.py output, keyed by id) when given, else a word-boundary regex fallback over
leak_terms(key) (check_phase7r_pilot.py's SYNONYMS/leak_terms, reused) for the gold label vs every other
option; disagreements/ambiguous-signal rows are dropped and counted per type (rule 1).

Splice (rule 2, decision rows only): scan `thinking` line by line; the first line whose text contains a
leak_terms hit for gold_label, EXCLUDING lines that merely enumerate options (>=2 distinct option keys
named in one line), is the "commit line". If that line starts before char 150, or no such line exists, the
row is dropped (no valid splice point). Otherwise the char offset of that line's start is the splice point:
everything in `thinking` from there on is dropped and replaced with
`<|decide:TYPE|>{injected}{tail}`, where `injected` is build_phase7r.py's exact
"{instruction} [{described options}]<|result|>{gold}<|/result|>" (same function, build_reasoning, reused)
and `tail` is one of ~12 short templates naming the label naturally, chosen deterministically per row id.
The organic ANSWER is kept verbatim; thinking_long = the unmodified organic thinking (token-saving
comparison baseline).

Control rows (rule 3, kind != "decision"): kept with organic thinking+answer completely unchanged, no
trigger -- teaches the model not to fire the trigger on ordinary turns.

Output schema (rule 4): the same per-row schema build_phase7r.py's assemble_row emits (so
train_phase7.py's encode_think / --think-calls --think-variant short works unchanged on this file), plus
source="H", organic_thinking_tokens, hybrid_thinking_tokens, saved_tokens, splice_char.

Usage (laptop, CPU, tokenizer only):
    python scripts/build_phase7r_hybrid.py build --organic oracle/t3-armB-think.fixed.jsonl \\
        --out oracle/phase7r-hybrid-dev-built.jsonl --dev
    python scripts/build_phase7r_hybrid.py validate --rows oracle/phase7r-hybrid-dev-built.jsonl --dev
"""
