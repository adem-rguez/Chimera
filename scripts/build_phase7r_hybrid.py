    if canon_errs:
        raise SystemExit(f"load_canonical errors: {canon_errs}")
    tok = get_tokenizer(args.model, args.revision)

    drop_reasons = collections.Counter()
    kept = []
    n_mentioned = n_checked = 0
    for rid, prow in prefixes.items():
        crow = conts.get(rid)
        if crow is None:
            drop_reasons["no_continuation"] += 1
            continue
        if not crow.get("finished"):
            drop_reasons["continuation_not_finished"] += 1
            continue
