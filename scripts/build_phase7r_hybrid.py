    if n_checked:
        print(f"  gold label surface mentioned in continuation (thinking tail + answer): "
              f"{n_mentioned}/{n_checked} ({n_mentioned / n_checked:.1%}) -- logged only, NOT a drop "
              f"filter; if it HAD been applied as a drop filter, {n_checked - n_mentioned} additional "
              f"row(s) would have been dropped")
    if kept:
        org = [r["organic_thinking_tokens"] for r in kept]
        hyb = [r["hybrid_thinking_tokens"] for r in kept]
        saved = [r["saved_tokens"] for r in kept]
        mean_org, mean_hyb = sum(org) / len(org), sum(hyb) / len(hyb)
        mean_saved = sum(saved) / len(saved)
        print(f"\n  thinking tokens: organic mean {mean_org:.1f}, hybrid mean {mean_hyb:.1f}, "
              f"saved mean {mean_saved:.1f} ({mean_saved / mean_org:.1%})")
        print("\n  3 decoded examples (around the splice AND the start of the continuation):")
        for r in kept[:3]:
            trig = TRIGGER_FOR[r["decision_types"][0]]
            idx = r["target_text_short"].find(trig)
            lo, hi = max(0, idx - 150), idx + len(trig) + 300
            print(f"\n    {r['id']} splice_char={r['splice_char']} saved={r['saved_tokens']} "
                  f"gold_mentioned={r['gold_mentioned']}:")
            print(f"    ...{r['target_text_short'][lo:hi]!r}...")
    return kept


