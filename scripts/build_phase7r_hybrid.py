def build2_row(tok, prow, cont_text, canonical):
    """-> (row dict, mention_bool) or raises ValueError for a drop condition the caller matches on
    message prefix (keeps the drop-reason bookkeeping in one place, in build2())."""
    if "<|decide:" in cont_text:
        raise ValueError("retrigger: continuation contains a second '<|decide:' trigger")
    close_idx = cont_text.find(THINK_CLOSE)
    if close_idx < 0:
        raise ValueError("no_close_marker: continuation never closes the thinking channel")
    if cont_text.find(THINK_CLOSE, close_idx + len(THINK_CLOSE)) >= 0:
        raise ValueError("malformed_channel: thinking channel closed more than once")
    if THINK_OPEN in cont_text:
        raise ValueError("malformed_channel: continuation reopens the thinking channel")

    thinking_tail = cont_text[:close_idx]
    answer = _strip_pad_and_turn(cont_text[close_idx + len(THINK_CLOSE):])
    if not answer:
        raise ValueError("empty_answer: continuation has no visible answer after the thinking channel")

    tname, gold = prow["type"], prow["gold_label"]
    instr, _opts = canonical[tname]
    options = [option_text(k, d) for k, d in prow["options_with_descriptions"]]
    calls = [{"type": tname, "instruction": instr, "options": options, "gold_label": gold}]

    reasoning_short = build_reasoning(calls, [prow["organic_kept"], thinking_tail])
    reasoning_long = prow["thinking_long"]

    full_short, plen_short = render_hybrid(tok, prow["user"], reasoning_short, answer)
    full_long, plen_long = render_hybrid(tok, prow["user"], reasoning_long, prow["organic_answer"])

    injected = injected_spans_typed(full_short)
    if injected_spans_typed(full_long):
        raise ValueError(f"{prow['id']}: thinking_long contains trigger/result markers")
    if len(injected) != 1:
        raise ValueError(f"bad_injected_spans: expected 1 injected span, found {len(injected)}")

    acct_short = token_accounting(tok, full_short, plen_short, injected)
    acct_long = token_accounting(tok, full_long, plen_long, [])
    masked_spans_short = [[0, plen_short]] + [[s, e] for s, e in injected]

    organic_tok = decoded_think_tokens(tok, reasoning_long)
    hybrid_tok = decoded_think_tokens(tok, reasoning_short)

    check_text = (thinking_tail + " " + answer).lower()
    terms = set(leak_terms(gold))
    mentioned = any(_word_hit([t], check_text) for t in terms if t)

    row = {
        "id": prow["id"], "kind": "call", "source": "H", "decision_types": [tname],
        "adversarial": False, "user": prow["user"],
        "calls": calls, "label_surfaces": {gold: label_surface(gold)}, "answer": answer,
        "thinking_segments": [prow["organic_kept"], thinking_tail], "thinking_long": reasoning_long,
        "target_text_short": full_short, "target_text_long": full_long,
        "masked_spans_short": masked_spans_short,
        "tokens_short": acct_short, "tokens_long": acct_long,
        "delta_supervised": acct_long["tokens_supervised"] - acct_short["tokens_supervised"],
        "delta_total": (acct_long["tokens_total"] - acct_long["tokens_prompt_masked"]) -
                        (acct_short["tokens_total"] - acct_short["tokens_prompt_masked"]),
        "organic_thinking_tokens": organic_tok, "hybrid_thinking_tokens": hybrid_tok,
        "saved_tokens": organic_tok - hybrid_tok,
        "splice_char": prow["splice_char"], "gold_mentioned": mentioned,
    }
    return row, mentioned


def build2(args):
    prefixes_path = args.prefixes if os.path.isabs(args.prefixes) else os.path.join(ROOT, args.prefixes)
    conts_path = args.continuations if os.path.isabs(args.continuations) else os.path.join(ROOT,
                                                                                              args.continuations)
    out_path = args.out if os.path.isabs(args.out) else os.path.join(ROOT, args.out)

    prefixes = {}
    with open(prefixes_path, encoding="utf-8") as f:
        for line in f:
            if line.strip():
                rec = json.loads(line)
