# tailprefix mode (v3 fix): the real continuation run (oracle/phase7r-hybrid-continuations.jsonl, see
# scripts/continue_phase7r_hybrid.py) showed the base model does NOT stop deliberating after the injected
# `<|result|>gold<|/result|>` -- it keeps re-analysing (hybrid thinking 394 tok vs organic 358, a NEGATIVE
# saving). Fix: append a short templated TAIL naming the result, then the model's OWN thinking-close
# marker (mirrored byte-for-byte off real organic raw_text -- see the inspection in this module's dev
# notes: the close marker directly follows the preceding sentence with NO extra newline, e.g.
# "...based on desired tone.<channel|>Here"), so the prefill FORCE-CLOSES the thinking channel and the
# base model can only continue by generating the visible answer.
