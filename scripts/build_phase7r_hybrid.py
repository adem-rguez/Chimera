def tailprefix_mode(args):
    prefixes_path = args.prefixes if os.path.isabs(args.prefixes) else os.path.join(ROOT, args.prefixes)
    out_path = args.out if os.path.isabs(args.out) else os.path.join(ROOT, args.out)

